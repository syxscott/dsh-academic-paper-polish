// Builds the offline data bundle for the preview harness.
//
//   node scripts/build-preview-data.mjs
//
// The preview page (`preview/panel.html`) loads the real `client.js` but has
// no host route, so every panel would render its empty state. This script
// produces `preview/preview-data.js`, which stubs the host API with the SAME
// data and the SAME engine output the real host produces:
//
//   - the rule / journal / checklist / sentence collections are the real files
//     in `data/`,
//   - the check / de-AI / outline responses are produced by running the real
//     `lib/` modules here, in Node, on a fixed sample text.
//
// So a screenshot of the preview is a screenshot of the production data, not a
// mock-up.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { join } from "node:path";

const ROOT = fileURLToPath(new URL("..", import.meta.url));

const { allRules, allJournals, allChecklists, allSentences, meta } = await import(
  pathToFileURL(join(ROOT, "lib", "data.mjs")).href
);
const { runPaperCheck, runPaperDeai, runPaperOutline } = await import(
  pathToFileURL(join(ROOT, "lib", "tools.mjs")).href
);

const SAMPLE = `Abstract: This paper delves into the fascinating world of radiolarians, which are
fascinating and amazing. We found that the radiolarians are very interesting. It is well known
that for the first time we have demonstrated this. Based on we suggest that this is important.
The dataset comprises 320 specimens collected from three sections.

Figure 1. Radiolarian assemblage from the Lower Jurassic. dpi: 150. 图宽: 220 mm. 字号: 6 pt.`;

const payload = {
  generatedFrom: "data/** + lib/** (real engine output)",
  meta: meta(),
  index: JSON.parse(readFileSync(join(ROOT, "skill-index.json"), "utf8")),
  rules: allRules(),
  journals: allJournals(),
  checklists: allChecklists(),
  sentences: allSentences(),
  demo: {
    sample: SAMPLE,
    check: runPaperCheck({ text: SAMPLE, section: "abstract", journal: "paleobiology" }),
    checkNoJournal: runPaperCheck({ text: SAMPLE, section: "abstract" }),
    deai: runPaperDeai({ text: SAMPLE }),
    outline: runPaperOutline({ journal: "paleobiology" }),
  },
};

const json = JSON.stringify(payload);
const out = `/* GENERATED by scripts/build-preview-data.mjs — do not edit by hand. */\nwindow.__PREVIEW_DATA__ = ${json};\n`;
const target = join(ROOT, "preview", "preview-data.js");
writeFileSync(target, out, "utf8");

console.log(`✓ wrote preview/preview-data.js (${(out.length / 1024).toFixed(0)} KB)`);
console.log(`  rules ${payload.rules.length} · journals ${payload.journals.length} · checklist stages ${payload.checklists.length} · sentences ${payload.sentences.length}`);
console.log(`  demo check: ${payload.demo.check.violations.length} violations, ${payload.demo.check.advice.length} advice`);
console.log(`  demo de-AI: score ${payload.demo.deai.score}, ${payload.demo.deai.hits.length} hits`);
